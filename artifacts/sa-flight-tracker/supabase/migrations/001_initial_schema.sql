-- SA Flight Tracker reference and live aircraft tables.
-- Safe to run on a new Supabase project; existing rows are preserved.

CREATE TABLE IF NOT EXISTS public.airports (
  airport_id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT,
  country TEXT NOT NULL,
  iata_code TEXT,
  icao_code TEXT,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  altitude INTEGER,
  timezone DOUBLE PRECISION,
  tz_database TEXT,
  type TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_airports_iata ON public.airports (iata_code);
CREATE INDEX IF NOT EXISTS idx_airports_icao ON public.airports (icao_code);
CREATE INDEX IF NOT EXISTS idx_airports_country ON public.airports (country);
CREATE INDEX IF NOT EXISTS idx_airports_location ON public.airports (latitude, longitude);

CREATE TABLE IF NOT EXISTS public.airlines (
  airline_id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  iata_code TEXT,
  icao_code TEXT,
  callsign TEXT,
  country TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_airlines_iata ON public.airlines (iata_code);
CREATE INDEX IF NOT EXISTS idx_airlines_icao ON public.airlines (icao_code);

CREATE TABLE IF NOT EXISTS public.routes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_key TEXT NOT NULL UNIQUE,
  airline_code TEXT NOT NULL,
  airline_id INTEGER,
  source_airport_code TEXT NOT NULL,
  source_airport_id INTEGER,
  destination_airport_code TEXT NOT NULL,
  destination_airport_id INTEGER,
  codeshare BOOLEAN NOT NULL DEFAULT FALSE,
  stops INTEGER NOT NULL DEFAULT 0,
  equipment TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_routes_source ON public.routes (source_airport_code);
CREATE INDEX IF NOT EXISTS idx_routes_destination ON public.routes (destination_airport_code);
CREATE INDEX IF NOT EXISTS idx_routes_airline ON public.routes (airline_code);

CREATE TABLE IF NOT EXISTS public.live_flights (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  icao24 TEXT NOT NULL UNIQUE,
  callsign TEXT,
  origin_country TEXT,
  longitude DOUBLE PRECISION,
  latitude DOUBLE PRECISION,
  baro_altitude DOUBLE PRECISION,
  geo_altitude DOUBLE PRECISION,
  on_ground BOOLEAN NOT NULL DEFAULT FALSE,
  velocity DOUBLE PRECISION,
  true_track DOUBLE PRECISION,
  vertical_rate DOUBLE PRECISION,
  squawk TEXT,
  spi BOOLEAN NOT NULL DEFAULT FALSE,
  position_source INTEGER,
  last_contact BIGINT,
  category INTEGER,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_live_flights_callsign ON public.live_flights (callsign);
CREATE INDEX IF NOT EXISTS idx_live_flights_location ON public.live_flights (latitude, longitude);
CREATE INDEX IF NOT EXISTS idx_live_flights_updated ON public.live_flights (updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_live_flights_on_ground ON public.live_flights (on_ground);

ALTER TABLE public.airports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.airlines ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.routes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.live_flights ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read airports" ON public.airports;
CREATE POLICY "Public read airports" ON public.airports
  FOR SELECT TO anon, authenticated USING (TRUE);

DROP POLICY IF EXISTS "Public read airlines" ON public.airlines;
CREATE POLICY "Public read airlines" ON public.airlines
  FOR SELECT TO anon, authenticated USING (TRUE);

DROP POLICY IF EXISTS "Public read routes" ON public.routes;
CREATE POLICY "Public read routes" ON public.routes
  FOR SELECT TO anon, authenticated USING (TRUE);

DROP POLICY IF EXISTS "Public read live_flights" ON public.live_flights;
CREATE POLICY "Public read live_flights" ON public.live_flights
  FOR SELECT TO anon, authenticated USING (TRUE);

DROP POLICY IF EXISTS "Service role write live_flights" ON public.live_flights;
CREATE POLICY "Service role write live_flights" ON public.live_flights
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);

GRANT SELECT ON public.airports, public.airlines, public.routes, public.live_flights
  TO anon, authenticated;
GRANT ALL ON public.airports, public.airlines, public.routes, public.live_flights
  TO service_role;

CREATE OR REPLACE FUNCTION public.cleanup_stale_flights()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  deleted_count INTEGER;
BEGIN
  DELETE FROM public.live_flights
  WHERE updated_at < NOW() - INTERVAL '30 minutes';
  GET DIAGNOSTICS deleted_count = ROW_COUNT;
  RETURN deleted_count;
END;
$$;

REVOKE ALL ON FUNCTION public.cleanup_stale_flights() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.cleanup_stale_flights() TO service_role;

CREATE OR REPLACE VIEW public.sa_airports
WITH (security_invoker = TRUE)
AS
SELECT *
FROM public.airports
WHERE country = 'South Africa'
  AND iata_code IS NOT NULL
  AND iata_code <> '\N'
ORDER BY city;

CREATE OR REPLACE VIEW public.sa_airlines
WITH (security_invoker = TRUE)
AS
SELECT *
FROM public.airlines
WHERE country = 'South Africa'
   OR icao_code IN ('SAA', 'SAX', 'KEM', 'CAW', 'LNK', 'MNU', 'FLE', 'CAA')
ORDER BY name;
